/** «بطاقة اليوم»: اختيار حتمي يعتمد على تاريخ اليوم */
export function cardOfDay(cards: ThinkingCard[], dayString: string): ThinkingCard | undefined {
  if (cards.length === 0) return undefined
  let h = 0x811c9dc5
  for (let i = 0; i < dayString.length; i++) {
    h ^= dayString.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return cards[Math.abs(h) % cards.length]
}
